    /// A frame of one byte, then a 16-byte block of four 65,539-byte matches of it (every table RLE, so its bit
    /// stream is only the matches' extra bits): 256 KB from one block, past the format's 128 KB.
    fn match_bomb(count: u8) -> Vec<u8> {
        let mut f = vec![0x28, 0xb5, 0x2f, 0xfd, 0x00, 0x00]; // (no content size: the window's byte)
        f.extend_from_slice(&[0x08, 0x00, 0x00, b'A']); // (a raw block of one byte)
        let bits = u32::from(count) * 18; // (each match: 2 bits of offset, 16 of length, all zero)
        let mut body = vec![0x00, count, 0x54, 0, 2, 52]; // (no literals; RLE tables: lengths 0, offset 1, matches 65539+)
        body.extend(std::iter::repeat_n(0u8, bits as usize / 8));
        body.push(1 << (bits % 8)); // (the stream's end marker, just past its last bit)
        let h = (body.len() as u32) << 3 | 2 << 1 | 1;
        f.extend_from_slice(&h.to_le_bytes()[..3]);
        f.extend(body);
        f
    }

    #[test]
    fn a_block_decodes_to_no_more_than_128_kb() {
        let bomb = match_bomb(4);
        let size = 1 + 4 * 65539;
        assert!(decompress(Dialect::Zstd, &bomb, size).is_err(), "four 64 KB matches in one block");
        assert!(prefix(Dialect::Zstd, &bomb, 10).is_err(), "nor when only its head is asked for");
        // (one match is a block of 64 KB: within the format)
        assert_eq!(decompress(Dialect::Zstd, &match_bomb(1), 1 + 65539).unwrap(), vec![b'A'; 1 + 65539]);
        assert!(decompress(Dialect::Zstd, &match_bomb(1), 1000).is_err(), "and no further than the size given");
    }

