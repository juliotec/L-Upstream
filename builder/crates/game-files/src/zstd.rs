//! zstd frames (RFC 8878), decoded whole, in two dialects: zstd's own and ZBIC.
//!
//! ZBIC is the code modules' compression from Switch firmware 22.0.0 on (an NSO's flags bit 7): a zstd frame with the
//! magic `ZBIC` whose FSE tables are written with binary interpolative coding (Moffat and Stuiver's) in place of
//! zstd's own count format. Everything else of the frame is zstd's. This is a decoder of that format, written from its
//! description below; it needs no C library. The .nup's own zstd frames (streamed, many GB) go through `ruzstd`
//! instead ([`crate::nup`]); this one decodes a module's segment, which is whole in memory.
//!
//! A ZBIC count table: its first byte holds a flag in bit 7 ("low probabilities": every count is one less than
//! coded, so -1 can be said) and in bits 0..7 the number `n` of bytes that follow. Those bytes are one number in mixed
//! radix, read from the last of them toward the first: digits are taken from the bottom of a window of at least 40
//! bits, which is refilled a byte at a time from the top. In order: the highest symbol (radix 52), the table's log
//! less 5 (radix 8), the cumulative count of the last symbol (radix 2^log), then the cumulative counts of the others,
//! by bisection of `0..2^k` (the power of two above the highest symbol), each digit within the bounds its interval's
//! ends already have. Every byte must be used.
//!
//! Provenance: written for Longshot from the format's description above and RFC 8878; no code is copied. The only
//! other implementation of ZBIC is Atmosphere-NX's (GPLv2, vendored as a separate tool in `third_party/zbic`): its
//! bisection order is a precomputed table there, and here it is generated by code (`bisection`), checked equal to
//! that table entry for entry when this was written. Verified by: zstd's own frames (`testdata/`, made by the zstd
//! command at levels 1 and 22, every block and literals form) and ruzstd's; a ZBIC count table round trip
//! (`a_zbic_count_table_reads_back`); and the game's ZBIC `main` on the PC it was written on, whose segments' SHA-256s
//! (in its NSO header, [`crate::nso`]) and plain bytes matched the C decoder's.

use std::fmt;

/// Why a frame could not be decoded.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ZstdError(pub String);

impl fmt::Display for ZstdError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(&self.0)
    }
}

impl std::error::Error for ZstdError {}

type Result<T> = std::result::Result<T, ZstdError>;

fn bad<T>(what: impl Into<String>) -> Result<T> {
    Err(ZstdError(what.into()))
}

/// Which dialect a frame is in.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Dialect {
    /// zstd's own (magic 0xFD2FB528).
    Zstd,
    /// ZBIC (magic `ZBIC`): binary interpolative count tables.
    Zbic,
}

impl Dialect {
    fn magic(self) -> u32 {
        match self {
            Dialect::Zstd => 0xFD2F_B528,
            Dialect::Zbic => 0x4349_425A,
        }
    }
}

/// zstd's magic, as the bytes a frame starts with.
pub const MAGIC: [u8; 4] = [0x28, 0xb5, 0x2f, 0xfd];

/// Whether a file starting with `head` (its first 4 bytes) starts as zstd data: a frame, or a skippable frame (magic
/// 0x184D2A50 to 0x184D2A5F).
pub fn starts_as_zstd(head: &[u8]) -> bool {
    head == MAGIC || (head.len() == 4 && head[1..] == [0x2a, 0x4d, 0x18] && head[0] & 0xf0 == 0x50)
}

/// The content size a zstd frame's header (its first 18 bytes, or fewer) states, `None` when it states none or is not
/// a zstd frame.
pub fn frame_content_size(head: &[u8]) -> Option<u64> {
    if head.len() < 18 || head[..4] != MAGIC {
        return None;
    }
    let fhd = head[4];
    let single = (fhd >> 5) & 1 == 1;
    let at = 5 + usize::from(!single) + [0, 1, 2, 4][usize::from(fhd & 3)];
    let n = [usize::from(single), 2, 4, 8][usize::from(fhd >> 6)];
    if n == 0 {
        return None;
    }
    let mut v = 0u64;
    for (i, b) in head[at..at + n].iter().enumerate() {
        v |= u64::from(*b) << (8 * i);
    }
    Some(if n == 2 { v + 256 } else { v })
}

/// Every frame of `src` decoded into one buffer, of `size` bytes exactly (an NSO segment's size).
pub fn decompress(dialect: Dialect, src: &[u8], size: usize) -> Result<Vec<u8>> {
    let mut out = Vec::with_capacity(size);
    let mut at = 0;
    while at < src.len() {
        let magic = read_u32(src, at)?;
        if magic & 0xFFFF_FFF0 == 0x184D_2A50 {
            let n = read_u32(src, at + 4)? as usize;
            at = at
                .checked_add(8 + n)
                .filter(|&e| e <= src.len())
                .ok_or_else(|| ZstdError("a skippable frame ends past the data".into()))?;
            continue;
        }
        if magic != dialect.magic() {
            return bad(format!("not a frame (magic {magic:#010x}) at byte {at}"));
        }
        at = frame(dialect, src, at + 4, &mut out, size, None)?;
    }
    if out.len() != size {
        return bad(format!("{} bytes decoded, {size} expected", out.len()));
    }
    Ok(out)
}

/// The first `n` bytes (or fewer, when it holds fewer) that the frame at the start of `src` holds: only the blocks
/// that make them are decoded, so `src` need hold no more than those (a file's head, read without its whole frame).
pub fn prefix(dialect: Dialect, src: &[u8], n: usize) -> Result<Vec<u8>> {
    if read_u32(src, 0)? != dialect.magic() {
        return bad("not a frame");
    }
    let mut out = Vec::new();
    frame(dialect, src, 4, &mut out, usize::MAX, Some(n))?;
    out.truncate(n);
    Ok(out)
}

fn read_u32(src: &[u8], at: usize) -> Result<u32> {
    match src.get(at..at + 4) {
        Some(b) => Ok(u32::from_le_bytes([b[0], b[1], b[2], b[3]])),
        None => bad("the data ends inside a frame's header"),
    }
}

fn take<'a>(src: &'a [u8], at: usize, n: usize, what: &str) -> Result<&'a [u8]> {
    src.get(at..at.saturating_add(n)).ok_or_else(|| ZstdError(format!("the data ends inside {what}")))
}

/// What a frame keeps from one block to the next.
struct FrameState {
    huffman: Option<Huffman>,
    tables: [Option<Fse>; 3],
    reps: [usize; 3],
}

/// One frame (after its magic, at `at`) decoded onto `out`; where it ends.
fn frame(
    dialect: Dialect,
    src: &[u8],
    mut at: usize,
    out: &mut Vec<u8>,
    limit: usize,
    stop: Option<usize>,
) -> Result<usize> {
    let fhd = take(src, at, 1, "a frame header")?[0];
    at += 1;
    if fhd & 0x08 != 0 {
        return bad("a frame header's reserved bit is set");
    }
    let single = fhd & 0x20 != 0;
    if !single {
        at += 1; // (the window: the whole output is the window here)
    }
    let dict = [0, 1, 2, 4][usize::from(fhd & 3)];
    if take(src, at, dict, "a frame header")?.iter().any(|&b| b != 0) {
        return bad("a frame needs a dictionary");
    }
    at += dict;
    let fcs_len = [usize::from(single), 2, 4, 8][usize::from(fhd >> 6)];
    let fcs = take(src, at, fcs_len, "a frame header")?.iter().rev().fold(0u64, |v, &b| v << 8 | u64::from(b));
    let content = (fcs_len > 0).then_some(if fcs_len == 2 { fcs + 256 } else { fcs });
    at += fcs_len;
    let start = out.len();
    let mut st = FrameState { huffman: None, tables: [None, None, None], reps: [1, 4, 8] };
    loop {
        let h = take(src, at, 3, "a block header")?;
        let h = u32::from(h[0]) | u32::from(h[1]) << 8 | u32::from(h[2]) << 16;
        at += 3;
        let (last, kind, size) = (h & 1 == 1, (h >> 1) & 3, (h >> 3) as usize);
        if size > 1 << 17 {
            return bad("a block is larger than 128 KB");
        }
        match kind {
            0 => out.extend_from_slice(take(src, at, size, "a raw block")?),
            1 => {
                let b = take(src, at, 1, "an RLE block")?[0];
                out.resize(out.len() + size, b);
            }
            2 => block(dialect, take(src, at, size, "a compressed block")?, out, start, limit, &mut st)?,
            _ => return bad("a reserved block type"),
        }
        at += if kind == 1 { 1 } else { size };
        if out.len() > limit {
            return bad(format!("the data decodes past its {limit} bytes"));
        }
        if last || stop.is_some_and(|s| out.len() - start >= s) {
            if !last {
                return Ok(at);
            }
            break;
        }
    }
    if fhd & 0x04 != 0 {
        take(src, at, 4, "a frame's checksum")?; // (not checked: an NSO's segments carry SHA-256 hashes, crate::nso)
        at += 4;
    }
    if let Some(n) = content
        && (out.len() - start) as u64 != n
    {
        return bad(format!("a frame decoded to {} bytes, its header says {n}", out.len() - start));
    }
    Ok(at)
}

// ---- bits

/// A bit stream read forward, from bit 0 of byte 0 (count tables).
struct Forward<'a> {
    data: &'a [u8],
    bit: usize,
}

impl Forward<'_> {
    fn read(&mut self, n: u32) -> u32 {
        let mut v = 0u32;
        for i in 0..n as usize {
            let b = self.bit + i;
            let byte = self.data.get(b / 8).copied().unwrap_or(0);
            v |= u32::from((byte >> (b % 8)) & 1) << i;
        }
        self.bit += n as usize;
        v
    }
}

/// A bit stream read backward from its end marker (Huffman and FSE streams): bits past its start read as zeros.
struct Backward<'a> {
    data: &'a [u8],
    /// The bits not read yet; below zero once more were read than it holds.
    left: i64,
}

impl<'a> Backward<'a> {
    fn new(data: &'a [u8]) -> Result<Backward<'a>> {
        match data.last() {
            Some(&b) if b != 0 => Ok(Backward { data, left: data.len() as i64 * 8 - i64::from(b.leading_zeros()) - 1 }),
            _ => bad("a bit stream without its end marker"),
        }
    }

    /// Bits `start..start + n` (n up to 56), bits below 0 zeros.
    fn bits_at(&self, start: i64, n: u32) -> u64 {
        if n == 0 {
            return 0;
        }
        if start < 0 {
            let missing = (-start) as u32;
            return if missing >= n { 0 } else { self.bits_at(0, n - missing) << missing };
        }
        let (byte, shift) = ((start / 8) as usize, (start % 8) as u32);
        let word = match self.data.get(byte..byte + 8) {
            Some(b) => u64::from_le_bytes(b.try_into().unwrap_or([0; 8])),
            None => {
                let mut b = [0u8; 8];
                let have = self.data.len().saturating_sub(byte).min(8);
                b[..have].copy_from_slice(&self.data[byte..byte + have]);
                u64::from_le_bytes(b)
            }
        };
        (word >> shift) & ((1u64 << n) - 1)
    }

    fn peek(&self, n: u32) -> u64 {
        self.bits_at(self.left - i64::from(n), n)
    }

    fn read(&mut self, n: u32) -> u64 {
        let v = self.peek(n);
        self.left -= i64::from(n);
        v
    }
}

fn high_bit(v: u32) -> u32 {
    31 - v.leading_zeros()
}

// ---- FSE

#[derive(Clone, Copy, Default)]
struct Cell {
    symbol: u8,
    bits: u8,
    base: u16,
}

/// An FSE decoding table.
#[derive(Clone)]
struct Fse {
    log: u32,
    cells: Vec<Cell>,
}

impl Fse {
    /// The table of these normalised counts (-1: "less than one") at accuracy `log` (RFC 8878, 4.1.1).
    fn new(counts: &[i16], log: u32) -> Result<Fse> {
        let size = 1usize << log;
        let mut cells = vec![Cell::default(); size];
        let mut next = vec![0u32; counts.len()];
        let mut high = size;
        // (a count is -1 ("less than one": a cell of its own at the top) or more; the cells are exactly filled)
        let filled: i64 = counts.iter().map(|&c| i64::from(c.max(0))).sum();
        if counts.iter().any(|&c| c < -1) || filled + counts.iter().filter(|&&c| c == -1).count() as i64 != size as i64
        {
            return bad("an FSE table's counts do not fill it");
        }
        for (s, &c) in counts.iter().enumerate() {
            if c == -1 {
                high = high.checked_sub(1).ok_or_else(|| ZstdError("an FSE table over its size".into()))?;
                cells[high].symbol = s as u8;
                next[s] = 1;
            } else {
                next[s] = c.max(0) as u32;
            }
        }
        let (step, mask) = ((size >> 1) + (size >> 3) + 3, size - 1);
        let mut pos = 0usize;
        for (s, &c) in counts.iter().enumerate() {
            for _ in 0..c.max(0) {
                cells[pos].symbol = s as u8;
                pos = (pos + step) & mask;
                while pos >= high {
                    pos = (pos + step) & mask;
                }
            }
        }
        if pos != 0 {
            return bad("an FSE table's counts do not fill it");
        }
        for cell in &mut cells {
            let s = usize::from(cell.symbol);
            let n = next[s];
            if n == 0 {
                return bad("an FSE table's cell of a symbol with no count");
            }
            next[s] += 1;
            let bits = log - high_bit(n);
            cell.bits = bits as u8;
            cell.base = ((n << bits) as usize - size) as u16;
        }
        Ok(Fse { log, cells })
    }

    /// One symbol's table (RLE mode).
    fn single(symbol: u8) -> Fse {
        Fse { log: 0, cells: vec![Cell { symbol, bits: 0, base: 0 }] }
    }

    /// A table read from `src` in the dialect's count format: the table and the bytes it took.
    fn read(dialect: Dialect, src: &[u8], max_symbol: usize, max_log: u32) -> Result<(Fse, usize)> {
        let (counts, log, used) = match dialect {
            Dialect::Zstd => counts_zstd(src, max_symbol)?,
            Dialect::Zbic => counts_zbic(src, max_symbol)?,
        };
        if log > max_log {
            return bad(format!("an FSE table's log {log} is over {max_log}"));
        }
        Ok((Fse::new(&counts, log)?, used))
    }
}

/// zstd's count format (RFC 8878, 4.1.1): counts, accuracy log, bytes used.
fn counts_zstd(src: &[u8], max_symbol: usize) -> Result<(Vec<i16>, u32, usize)> {
    let mut bits = Forward { data: src, bit: 0 };
    let log = bits.read(4) + 5;
    if log > 15 {
        return bad("an FSE table's log is over 15");
    }
    let mut remaining = 1i32 << log;
    let mut counts = Vec::new();
    while remaining > 0 {
        if counts.len() > max_symbol {
            return bad("an FSE table has more symbols than its kind");
        }
        let n = high_bit((remaining + 1) as u32) + 1;
        let lower = (1u32 << (n - 1)) - 1;
        let threshold = (1u32 << n) - 1 - (remaining as u32 + 1);
        let mut v = bits.read(n);
        if v & lower < threshold {
            bits.bit -= 1;
            v &= lower;
        } else if v > lower {
            v -= threshold;
        }
        let count = v as i16 - 1;
        remaining -= i32::from(count.abs());
        counts.push(count);
        if count == 0 {
            loop {
                let repeat = bits.read(2);
                counts.extend(std::iter::repeat_n(0, repeat as usize));
                if repeat != 3 {
                    break;
                }
            }
        }
    }
    let used = bits.bit.div_ceil(8);
    if remaining != 0 || counts.len() > max_symbol + 1 || used > src.len() {
        return bad("an FSE table's counts are damaged");
    }
    Ok((counts, log, used))
}

/// Digits of a ZBIC count table's number (the module docs): taken from the bottom, refilled from the top.
struct Digits<'a> {
    src: &'a [u8],
    left: usize,
    window: u64,
}

impl Digits<'_> {
    fn refill(&mut self) {
        while self.left != 0 && self.window < 1 << 40 {
            self.window = self.window << 8 | u64::from(self.src[self.left]);
            self.left -= 1;
        }
    }

    fn take(&mut self, radix: u64) -> u64 {
        let d = self.window % radix;
        self.window /= radix;
        self.refill();
        d
    }
}

/// The intervals of `0..top` in the order ZBIC codes their midpoints: each interval's midpoint, then its upper half,
/// then its lower half, and last the interval `0..1`.
fn bisection(top: u32) -> Vec<(u32, u32, u32)> {
    fn visit(lo: u32, hi: u32, out: &mut Vec<(u32, u32, u32)>) {
        if hi - lo >= 2 {
            let mid = (lo + hi) / 2;
            out.push((mid, lo, hi));
            visit(mid, hi, out);
            visit(lo, mid, out);
        }
    }
    let mut out = Vec::with_capacity(top as usize);
    visit(0, top, &mut out);
    out.push((0, 0, 1));
    out
}

/// ZBIC's count format: counts, accuracy log, bytes used.
fn counts_zbic(src: &[u8], max_symbol: usize) -> Result<(Vec<i16>, u32, usize)> {
    let Some(&first) = src.first() else { return bad("an empty ZBIC count table") };
    let n = usize::from(first & 0x7f);
    let low = u32::from(first >> 7);
    if n + 1 >= src.len() {
        return bad("a ZBIC count table ends past its block");
    }
    let mut d = Digits { src, left: n, window: 0 };
    d.refill();
    let highest = d.take(0x34) as u32 + 1;
    if highest as usize > max_symbol {
        return bad("a ZBIC count table has more symbols than its kind");
    }
    let log = d.take(8) as u32 + 5;
    let last = d.take(1 << log) as u32 + 1 + if low == 1 { highest + 1 } else { 0 };
    let top = (highest + 1).next_power_of_two();
    let mut cum = [0u32; 257];
    cum[top as usize] = last;
    for (mid, lo, hi) in bisection(top) {
        let (a, b) = (cum[lo as usize], cum[hi as usize]);
        if a == b {
            cum[lo as usize + 1..hi as usize].fill(a);
        } else if b < a {
            return bad("a ZBIC count table's counts go down");
        } else {
            cum[mid as usize] = d.take(u64::from(b - a) + 1) as u32 + a;
        }
    }
    if d.left != 0 {
        return bad("a ZBIC count table has bytes left over");
    }
    // (the counts are the differences of the cumulative ones, from 0: cum[0] was the last interval's digit only)
    let mut counts = Vec::with_capacity(highest as usize + 1);
    let mut remaining = 1i64 << log;
    let mut prev = 0i64;
    for &c in &cum[1..=highest as usize + 1] {
        let count = i64::from(c) - prev - i64::from(low);
        prev = i64::from(c);
        if count < -1 {
            return bad("a ZBIC count below -1");
        }
        remaining -= count.abs();
        counts.push(i16::try_from(count).map_err(|_| ZstdError("a ZBIC count out of range".into()))?);
    }
    if remaining != 0 {
        return bad("a ZBIC count table's counts do not add up");
    }
    Ok((counts, log, n + 1))
}

// ---- Huffman

#[derive(Clone)]
struct Huffman {
    max_bits: u32,
    /// By the next `max_bits` bits: the symbol and its length.
    table: Vec<(u8, u8)>,
}

impl Huffman {
    /// A tree description (RFC 8878, 4.2.1): the table and the bytes it took.
    fn read(dialect: Dialect, src: &[u8]) -> Result<(Huffman, usize)> {
        let header = usize::from(take(src, 0, 1, "a Huffman tree")?[0]);
        let mut weights = Vec::with_capacity(256);
        let used = if header >= 128 {
            let n = header - 127;
            let bytes = take(src, 1, n.div_ceil(2), "a Huffman tree")?;
            weights.extend((0..n).map(|i| if i % 2 == 0 { bytes[i / 2] >> 4 } else { bytes[i / 2] & 15 }));
            1 + n.div_ceil(2)
        } else {
            let body = take(src, 1, header, "a Huffman tree")?;
            let (fse, used) = Fse::read(dialect, body, 255, 6)?;
            let mut bits = Backward::new(&body[used..])?;
            let mut states = [bits.read(fse.log) as usize, bits.read(fse.log) as usize];
            // (two states in turn, until the stream is read past its start: then the other's symbol is the last)
            'weights: loop {
                for k in 0..2 {
                    let cell = fse.cells[states[k]];
                    weights.push(cell.symbol);
                    states[k] = usize::from(cell.base) + bits.read(u32::from(cell.bits)) as usize;
                    if bits.left < 0 {
                        weights.push(fse.cells[states[1 - k]].symbol);
                        break 'weights;
                    }
                    if weights.len() > 255 {
                        return bad("a Huffman tree with too many weights");
                    }
                }
            }
            1 + header
        };
        if weights.iter().any(|&w| w > 12) {
            return bad("a Huffman weight over 12");
        }
        let sum: u32 = weights.iter().filter(|&&w| w > 0).map(|&w| 1u32 << (w - 1)).sum();
        if sum == 0 {
            return bad("a Huffman tree without weights");
        }
        let max_bits = high_bit(sum) + 1;
        let rest = (1u32 << max_bits) - sum;
        if !rest.is_power_of_two() || max_bits > 12 || weights.len() > 255 {
            return bad("a Huffman tree's weights are damaged");
        }
        weights.push((high_bit(rest) + 1) as u8);
        let lengths: Vec<u32> = weights.iter().map(|&w| if w == 0 { 0 } else { max_bits + 1 - u32::from(w) }).collect();
        let mut rank = vec![0usize; max_bits as usize + 2];
        for &l in &lengths {
            if l > 0 {
                rank[l as usize] += 1;
            }
        }
        let mut start = vec![0usize; max_bits as usize + 2];
        for l in (1..=max_bits as usize).rev() {
            start[l - 1] = start[l] + rank[l] * (1usize << (max_bits as usize - l));
        }
        let mut table = vec![(0u8, 0u8); 1 << max_bits];
        for (s, &l) in lengths.iter().enumerate() {
            if l > 0 {
                let n = 1usize << (max_bits - l);
                let at = start[l as usize];
                table[at..at + n].fill((s as u8, l as u8));
                start[l as usize] += n;
            }
        }
        Ok((Huffman { max_bits, table }, used))
    }

    /// One stream of `n` symbols onto `out`.
    fn stream(&self, src: &[u8], n: usize, out: &mut Vec<u8>) -> Result<()> {
        let mut bits = Backward::new(src)?;
        for _ in 0..n {
            let (s, l) = self.table[bits.peek(self.max_bits) as usize];
            out.push(s);
            bits.left -= i64::from(l);
        }
        if bits.left != 0 {
            return bad("a Huffman stream does not end with its symbols");
        }
        Ok(())
    }
}

// ---- blocks

/// The literals section at the start of a compressed block: the literals, and where the sequences start.
fn literals(dialect: Dialect, src: &[u8], st: &mut FrameState) -> Result<(Vec<u8>, usize)> {
    let b0 = take(src, 0, 1, "a literals section")?[0];
    let (kind, format) = (b0 & 3, (b0 >> 2) & 3);
    if kind < 2 {
        let (head, size) = match format {
            0 | 2 => (1, usize::from(b0 >> 3)),
            1 => (2, usize::from(b0 >> 4) | usize::from(take(src, 1, 1, "a literals header")?[0]) << 4),
            _ => {
                let b = take(src, 1, 2, "a literals header")?;
                (3, usize::from(b0 >> 4) | usize::from(b[0]) << 4 | usize::from(b[1]) << 12)
            }
        };
        return Ok(if kind == 0 {
            (take(src, head, size, "raw literals")?.to_vec(), head + size)
        } else {
            (vec![take(src, head, 1, "RLE literals")?[0]; size], head + 1)
        });
    }
    let (head, width, streams) = match format {
        0 => (3, 10, 1),
        1 => (3, 10, 4),
        2 => (4, 14, 4),
        _ => (5, 18, 4),
    };
    let h = take(src, 0, head, "a literals header")?.iter().rev().fold(0u64, |v, &b| v << 8 | u64::from(b));
    let mask = (1u64 << width) - 1;
    let (regen, comp) = (((h >> 4) & mask) as usize, ((h >> (4 + width)) & mask) as usize);
    if regen > 1 << 17 {
        return bad("literals larger than 128 KB");
    }
    let mut body = take(src, head, comp, "compressed literals")?;
    if kind == 2 {
        let (huffman, used) = Huffman::read(dialect, body)?;
        st.huffman = Some(huffman);
        body = &body[used..];
    }
    let huffman = st.huffman.as_ref().ok_or_else(|| ZstdError("repeated literals with no table before".into()))?;
    let mut out = Vec::with_capacity(regen);
    if streams == 1 {
        huffman.stream(body, regen, &mut out)?;
    } else {
        let jump = take(body, 0, 6, "a literals jump table")?;
        let sizes = [0, 2, 4].map(|i| usize::from(jump[i]) | usize::from(jump[i + 1]) << 8);
        let each = regen.div_ceil(4);
        let mut at = 6;
        for (i, &n) in sizes.iter().enumerate() {
            huffman.stream(take(body, at, n, "a literals stream")?, each, &mut out)?;
            at += n;
            let _ = i;
        }
        let last = regen.checked_sub(3 * each).ok_or_else(|| ZstdError("literals too few for four streams".into()))?;
        huffman.stream(body.get(at..).unwrap_or_default(), last, &mut out)?;
    }
    Ok((out, head + comp))
}

