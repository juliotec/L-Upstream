//! The files the build writes itself and compiles: the start-up screen's logo, the bundled fonts, ReShade's adapted
//! preprocessor, the Windows resources ([`res`]), the version line ([`version`]) and the shader translator's stamp
//! ([`shader_stamp`]). Each is written only when its bytes change, so an unchanged one keeps its date.

pub mod res;
pub mod shader_stamp;
pub mod version;

use build_core::{Error, IoContext, Result, fsx};
use std::fmt::Write as _;
use std::path::Path;

/// `bytes` as the lines of a C array's body, `per_line` values a line, each line ending in a comma.
fn c_bytes(out: &mut String, bytes: &[u8], per_line: usize) {
    for chunk in bytes.chunks(per_line) {
        let line: Vec<String> = chunk.iter().map(u8::to_string).collect();
        let _ = writeln!(out, "{},", line.join(","));
    }
}

/// The start-up screen's logo: `assets/longshot.png` as straight RGBA bytes in a header; without
/// the picture, a header that says so (the screen then shows the wordmark alone).
pub fn logo_header(png: &Path) -> Result<String> {
    let Ok(data) = std::fs::read(png) else {
        return Ok("// generated by longshot-builder: no assets/longshot.png\n#pragma once\n".to_string());
    };
    let (w, h, px) = decode_png(&data).map_err(|e| Error::format(png.display().to_string(), e))?;
    let mut out =
        String::from("// generated by longshot-builder from assets/longshot.png: do not edit\n#pragma once\n");
    out.push_str("#define LONGSHOT_LOGO 1\n");
    let _ = writeln!(out, "static const unsigned longshot_logo_w = {w}, longshot_logo_h = {h};");
    let _ = writeln!(out, "static const unsigned char longshot_logo_rgba[{}] = {{", px.len());
    c_bytes(&mut out, &px, 32);
    out.push_str("};\n");
    Ok(out)
}

/// (width, height, RGBA bytes) of an 8-bit, non-interlaced RGB or RGBA PNG: what the logo is.
pub fn decode_png(data: &[u8]) -> std::result::Result<(u32, u32, Vec<u8>), String> {
    if !data.starts_with(b"\x89PNG\r\n\x1a\n") {
        return Err("not a PNG".into());
    }
    let (mut at, mut idat, mut head) = (8, Vec::new(), None);
    while at + 8 <= data.len() {
        let n = u32::from_be_bytes(data[at..at + 4].try_into().unwrap_or_default()) as usize;
        let kind = &data[at + 4..at + 8];
        let body = data.get(at + 8..at + 8 + n).ok_or("a chunk cut short")?;
        match kind {
            b"IHDR" if n >= 13 => head = Some(body.to_vec()),
            b"IDAT" => idat.extend_from_slice(body),
            b"IEND" => break,
            _ => {}
        }
        at += 12 + n;
    }
    let head = head.ok_or("no header")?;
    let w = u32::from_be_bytes(head[0..4].try_into().unwrap_or_default());
    let h = u32::from_be_bytes(head[4..8].try_into().unwrap_or_default());
    let (depth, colour, interlace) = (head[8], head[9], head[12]);
    if depth != 8 || !matches!(colour, 2 | 6) || interlace != 0 {
        return Err(format!("only 8-bit RGB/RGBA, not interlaced: depth {depth}, colour {colour}"));
    }
    let bpp = if colour == 6 { 4 } else { 3 };
    let raw = miniz_oxide::inflate::decompress_to_vec_zlib(&idat).map_err(|e| format!("{e:?}"))?;
    let stride = w as usize * bpp;
    if raw.len() < h as usize * (stride + 1) {
        return Err("pixels cut short".into());
    }
    let mut out = Vec::with_capacity(w as usize * h as usize * 4);
    let mut prev = vec![0u8; stride];
    for y in 0..h as usize {
        let f = raw[y * (stride + 1)];
        let mut line = raw[y * (stride + 1) + 1..(y + 1) * (stride + 1)].to_vec();
        for x in 0..stride {
            let a = if x >= bpp { line[x - bpp] as i32 } else { 0 };
            let b = prev[x] as i32;
            let c = if x >= bpp { prev[x - bpp] as i32 } else { 0 };
            let add = match f {
                1 => a,
                2 => b,
                3 => (a + b) >> 1,
                4 => {
                    let p = a + b - c;
                    let (pa, pb, pc) = ((p - a).abs(), (p - b).abs(), (p - c).abs());
                    if pa <= pb && pa <= pc {
                        a
                    } else if pb <= pc {
                        b
                    } else {
                        c
                    }
                }
                _ => 0,
            };
            line[x] = (line[x] as i32 + add) as u8;
        }
        if bpp == 4 {
            out.extend_from_slice(&line);
        } else {
            for px in line.chunks(3) {
                out.extend_from_slice(px);
                out.push(255);
            }
        }
        prev = line;
    }
    Ok((w, h, out))
}

/// The overlays' bundled fonts: third_party/fonts/libertinus's TTF files as byte arrays in a C++ file,
/// compiled into the renderer. They stand in when the player's game files lack the game's menu font.
pub fn fonts_cpp(fonts: &Path) -> Result<String> {
    const FILES: [(&str, &str); 3] = [
        ("longshot_font_body", "LibertinusSans-Regular.ttf"),
        ("longshot_font_strong", "LibertinusSans-Bold.ttf"),
        ("longshot_font_heading", "LibertinusSerif-Semibold.ttf"),
    ];
    let mut out = String::from(
        "// generated by longshot-builder from third_party/fonts/libertinus (SIL Open Font License 1.1): do not edit\n",
    );
    for (name, file) in FILES {
        let p = fonts.join(file);
        let data = std::fs::read(&p).at(&p)?;
        let _ = writeln!(out, "extern const unsigned {name}_size = {};", data.len());
        let _ = writeln!(out, "extern const unsigned char {name}[{}] = {{", data.len());
        c_bytes(&mut out, &data, 48);
        out.push_str("};\n");
    }
    Ok(out)
}

/// ReShade's preprocessor (`third_party/reshade_fx/source/effect_preprocessor.cpp`) adapted to read and resolve its
/// files through Longshot's asset reader: three text edits, each required to match once.
pub fn reshade_preprocessor(upstream: &Path) -> Result<String> {
    let source = upstream.join("effect_preprocessor.cpp");
    let mut text = std::fs::read_to_string(&source).at(&source)?;
    let what = source.display().to_string();
    let fail = |old: &str| {
        let head: String = old.chars().take(80).collect();
        Error::format(what.clone(), format!("update the ReShade include adapter: {head}"))
    };
    let replace = |text: &mut String, old: &str, new: &str| -> Result<()> {
        if text.matches(old).count() != 1 {
            return Err(fail(old));
        }
        *text = text.replacen(old, new, 1);
        Ok(())
    };
    let find_from = |text: &str, needle: &str, from: usize| text[from..].find(needle).map(|i| from + i);
    replace(
        &mut text,
        "#include \"effect_preprocessor.hpp\"",
        "#include \"effect_preprocessor.hpp\"\n#include \"fx_files.h\"",
    )?;
    let read = find_from(&text, "static bool read_file(", 0).ok_or_else(|| fail("static bool read_file("))?;
    let start =
        find_from(&text, "\t// Read file contents into memory\n", read).ok_or_else(|| fail("Read file contents"))?;
    let end = find_from(&text, "\t// Append a new line feed", start).ok_or_else(|| fail("Append a new line feed"))?;
    let old = text[start..end].to_string();
    replace(
        &mut text,
        &old,
        "\tif (!ls::reshade::read_fx_file(path, file_data))\n\t\treturn false;\n\tfile_data.push_back('\\n');\n\n",
    )?;
    let inc =
        find_from(&text, "void reshadefx::preprocessor::parse_include()", 0).ok_or_else(|| fail("parse_include"))?;
    let start = find_from(&text, "\tstd::filesystem::path file_name =", inc).ok_or_else(|| fail("file_name ="))?;
    let end =
        find_from(&text, "\tconst std::string file_path_string", start).ok_or_else(|| fail("file_path_string"))?;
    let old = text[start..end].to_string();
    replace(
        &mut text,
        &old,
        "\tconst auto file_name = std::filesystem::u8path(_token.literal_as_string);\n\
         \tconst auto file_path = ls::reshade::resolve_fx_include(\n\
         \t\tstd::filesystem::u8path(_output_location.source), file_name, _include_paths);\n\
         \tif (file_path.empty())\n\
         \t\treturn error(keyword_location, \"could not open included file '\" + _token.literal_as_string + '\\'');\n\n",
    )?;
    Ok(text)
}

/// `text` written at `path` when it differs.
pub fn write(path: &Path, text: &[u8]) -> Result<()> {
    fsx::write_if_changed(path, text).map(|_| ())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_png_s_filters_are_undone() {
        // (a 2x2 RGB picture, its rows filtered Sub and Paeth, made here)
        let rows: [u8; 14] = [1, 10, 20, 30, 5, 5, 5, 4, 1, 1, 1, 2, 2, 2];
        let z = miniz_oxide::deflate::compress_to_vec_zlib(&rows, 6);
        let mut png = b"\x89PNG\r\n\x1a\n".to_vec();
        let chunk = |png: &mut Vec<u8>, kind: &[u8], body: &[u8]| {
            png.extend((body.len() as u32).to_be_bytes());
            png.extend(kind);
            png.extend(body);
            png.extend([0; 4]); // (the CRC is not checked)
        };
        chunk(&mut png, b"IHDR", &[0, 0, 0, 2, 0, 0, 0, 2, 8, 2, 0, 0, 0]);
        chunk(&mut png, b"IDAT", &z);
        chunk(&mut png, b"IEND", &[]);
        let (w, h, px) = decode_png(&png).unwrap();
        assert_eq!((w, h), (2, 2));
        // (row 0, Sub: 10,20,30 then +5 each; row 1, Paeth from row 0)
        assert_eq!(px, [10, 20, 30, 255, 15, 25, 35, 255, 11, 21, 31, 255, 17, 27, 37, 255]);
    }
}
